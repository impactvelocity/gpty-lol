export type CostumeGroup = "Classic" | "Haunted" | "Other";

export interface Costume {
  id: string;
  name: string;
  year: string;
  group: CostumeGroup;
  layout: LayoutId;
  haunted: boolean;
  tagline: string;
  /** Display name of the assistant inside this costume. */
  assistant: string;
  /** Display name of the user inside this costume. */
  user: string;
  avatar: string;
  userAvatar: string;
  /** Shown as the assistant's opening line. Never sent to the model. */
  greeting: string;
  placeholder: string;
  send: string;
  typing: string;
  error: string;
  /** Two colors used for the wardrobe card. */
  swatch: [string, string];
  /** CSS custom properties applied to the costume wrapper. */
  palette: Record<string, string>;
}

